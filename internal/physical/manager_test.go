func TestPrivatePersistenceAndPublicViews(t *testing.T) {
	dir := t.TempDir()
	target := sesame.Target{UUID: "00112233-4455-6677-8899-aabbccddeeff", Model: "sesame_6_pro", Adapter: "hci0", Registered: true}
	id, _ := identity(target)
	record := Record{id, "Front door", "sesame", target}
	secret := "000102030405060708090a0b0c0d0e0f"
	os.Mkdir(filepath.Join(dir, "physical-lock-keys"), 0700)
	if e := writeJSON(filepath.Join(dir, "physical-lock-keys", id+".json"), sesame.Credential{Secret: secret}); e != nil {
		t.Fatal(e)
	}
	if e := writeJSON(filepath.Join(dir, "physical-locks.json"), []Record{record}); e != nil {
		t.Fatal(e)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	m, e := Open(ctx, dir, func(context.Context, sesame.Target) (sesame.Link, sesame.Target, error) {
		t.Error("dial after cancellation")
		return nil, sesame.Target{}, ctx.Err()
	})
	if e != nil {
		t.Fatal(e)
	}
	defer m.Close()
	b, _ := json.Marshal(m.Views())
	if strings.Contains(string(b), secret) || strings.Contains(string(b), "secret") {
		t.Fatal("public view leaks credentials")
	}
	if !m.Has(id) || m.Has("missing") {
		t.Fatal("registry lookup")
	}
	k, e := m.readKey(id)
	if e != nil || k.Secret != secret {
		t.Fatal("key not persisted")
	}
	for _, path := range []string{m.keyPath(id), filepath.Join(dir, "physical-locks.json")} {
		st, e := os.Stat(path)
		if e != nil || st.Mode().Perm() != 0600 {
			t.Fatal("unsafe file permissions", path)
		}
	}
	var records []Record
	b, _ = os.ReadFile(filepath.Join(dir, "physical-locks.json"))
	if e = json.Unmarshal(b, &records); e != nil || len(records) != 1 {
		t.Fatal("registry")
	}
}
