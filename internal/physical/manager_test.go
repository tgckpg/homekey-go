// The encrypted login response is an independent AESCCM fixture for the
// synthetic key/token in this test, not generated by the driver under test.
type importLink struct {
	packets chan []byte
	done    chan error
	sent    bool
}

func newImportLink() *importLink {
	l := &importLink{packets: make(chan []byte, 4), done: make(chan error)}
	l.packets <- []byte{3, 8, 14, 0x11, 0x22, 0x33, 0x44}
	return l
}
func (l *importLink) Packets() <-chan []byte { return l.packets }
func (l *importLink) Done() <-chan error     { return l.done }
func (l *importLink) Close()                 {}
func (l *importLink) Write(ctx context.Context, b []byte) error {
	if !l.sent {
		l.sent = true
		l.packets <- []byte{5, 0xbe, 0x9d, 0x51, 0x39, 0x09, 0xb8, 0x0b, 0x9e, 0x70, 0x6a, 0x5e}
	}
	return nil
}
func TestImportPersistsAndRestoresWithoutPublicSecret(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	dir := t.TempDir()
	dial := func(_ context.Context, target sesame.Target) (sesame.Link, sesame.Target, error) {
		target.Registered = true
		return newImportLink(), target, nil
	}
	m, e := Open(ctx, dir, dial)
	if e != nil {
		t.Fatal(e)
	}
	var in Enrollment
	raw := `{"name":"Door","mode":"import","target":{"uuid":"00112233-4455-6677-8899-aabbccddeeff","model":"sesame_6_pro","adapter":"hci0"},"key":{"deviceUUID":"00112233-4455-6677-8899-aabbccddeeff","deviceModel":"sesame_6_pro","secretKey":"000102030405060708090a0b0c0d0e0f"}}`
	if e = json.Unmarshal([]byte(raw), &in); e != nil {
		t.Fatal(e)
	}
	record, e := m.Add(ctx, in)
	if e != nil {
		m.Close()
		t.Fatal(e)
	}
	if !m.Has(record.ID) {
		t.Fatal("import missing")
	}
	if _, e = m.Add(ctx, in); e == nil {
		t.Fatal("duplicate import")
	}
	public, _ := json.Marshal(m.Views())
	if strings.Contains(string(public), in.Key.Secret) {
		t.Fatal("key leaked")
	}
	m.Close()
	m, e = Open(ctx, dir, dial)
	if e != nil {
		t.Fatal(e)
	}
	defer m.Close()
	if !m.Has(record.ID) {
		t.Fatal("import not restored")
	}
}
